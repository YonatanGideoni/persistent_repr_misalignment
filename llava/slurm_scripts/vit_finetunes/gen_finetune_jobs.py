# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

OUT_DIR = Path(__file__).resolve().parent  # slurm_scripts/vit_finetunes/
LLM_MODEL = "lmsys/vicuna-7b-v1.5"

PRETRAIN_BATCH = 128
PRETRAIN_GRAD_AC = 2
FINETUNE_BATCH = 32
FINETUNE_GRAD_AC = 4

# ---------------------------------------------------------------------------
# Script template
# ---------------------------------------------------------------------------

JOB_TEMPLATE = """\
#!/bin/bash
#SBATCH --cpus-per-task=16
#SBATCH --gres=gpu:1
#SBATCH --job-name="ft_{slug}"
#SBATCH --output=ft_{slug}.out
#SBATCH --error=ft_{slug}.err

set -a; [ -f ../.env ] && source ../.env; set +a  # credentials: copy ../.env.example to ../.env

# Generated by slurm_scripts/vit_finetunes/gen_finetune_jobs.py -- edit the generator, not this file.
# Submit from the llava/ release root: sbatch slurm_scripts/vit_finetunes/{slug}.job
# WANDB_API_KEY / HF_TOKEN / HF_HOME are read from the submitting environment.

# ── configurable ────────────────────────────────────────────────────────────
PRETRAIN_BATCH={pretrain_batch}
PRETRAIN_GRAD_AC={pretrain_grad_ac}
FINETUNE_BATCH={finetune_batch}
FINETUNE_GRAD_AC={finetune_grad_ac}
# LLaVA-1.5 training data (LLaVA-Pretrain/, llava_v1_5_mix665k.json and its image folders)
DATA_DIR=${{DATA_DIR:-/path/to/llava/playground/data}}
# Where pretrain (mm_projector.bin) and LoRA checkpoints are written
CKPT_DIR=${{CKPT_DIR:-/path/to/checkpoints}}
# ────────────────────────────────────────────────────────────────────────────

export NCCL_DEBUG=INFO

PRETRAIN_OUT="$CKPT_DIR/llava-v1.5-7b-pretrain-ft-{slug}"
FINETUNE_OUT="$CKPT_DIR/llava-v1.5-7b-lora-ft-{slug}"

# ── Skip if finetune already completed ───────────────────────────────────────
if [ -f "$FINETUNE_OUT/adapter_model.safetensors" ]; then
    echo "Finetune output already exists at $FINETUNE_OUT — skipping."
    exit 0
fi

# ── Stage 1: pretrain (feature alignment) ───────────────────────────────────
if [ -f "$PRETRAIN_OUT/mm_projector.bin" ]; then
    echo "Pretrain output already exists at $PRETRAIN_OUT — skipping stage 1."
else
srun deepspeed llava/train/train_mem.py \\
    --deepspeed ./scripts/zero2.json \\
    --model_name_or_path {llm_model} \\
    --version plain \\
    --data_path $DATA_DIR/LLaVA-Pretrain/blip_laion_cc_sbu_558k.json \\
    --image_folder $DATA_DIR/LLaVA-Pretrain/images \\
    --vision_tower {model_id} \\
    --mm_vision_tower_type {family} \\
    --mm_projector_type mlp2x_gelu \\
    --tune_mm_mlp_adapter True \\
    --mm_vision_select_layer -2 \\
    --mm_use_im_start_end False \\
    --mm_use_im_patch_token False \\
    --bf16 True \\
    --output_dir $PRETRAIN_OUT \\
    --num_train_epochs 1 \\
    --per_device_train_batch_size $PRETRAIN_BATCH \\
    --gradient_accumulation_steps $PRETRAIN_GRAD_AC \\
    --save_strategy no \\
    --learning_rate 1e-3 \\
    --weight_decay 0. \\
    --warmup_ratio 0.03 \\
    --lr_scheduler_type cosine \\
    --logging_steps 1 \\
    --tf32 True \\
    --model_max_length 2048 \\
    --gradient_checkpointing True \\
    --dataloader_num_workers 8 \\
    --lazy_preprocess True \\
    --report_to wandb
fi

# ── Guard: skip finetune if pretrain didn't produce mm_projector.bin ─────────
if [ ! -f "$PRETRAIN_OUT/mm_projector.bin" ]; then
    echo "ERROR: $PRETRAIN_OUT/mm_projector.bin not found — pretrain failed, skipping finetune."
    exit 1
fi

# ── Stage 2: finetune (LoRA) ─────────────────────────────────────────────────
srun deepspeed llava/train/train_mem.py \\
    --lora_enable True --lora_r 128 --lora_alpha 256 --mm_projector_lr 2e-5 \\
    --deepspeed ./scripts/zero2.json \\
    --model_name_or_path {llm_model} \\
    --version v1 \\
    --data_path $DATA_DIR/llava_v1_5_mix665k.json \\
    --image_folder $DATA_DIR \\
    --vision_tower {model_id} \\
    --mm_vision_tower_type {family} \\
    --pretrain_mm_mlp_adapter $PRETRAIN_OUT/mm_projector.bin \\
    --mm_projector_type mlp2x_gelu \\
    --mm_vision_select_layer -2 \\
    --mm_use_im_start_end False \\
    --mm_use_im_patch_token False \\
    --image_aspect_ratio pad \\
    --group_by_modality_length True \\
    --bf16 True \\
    --output_dir $FINETUNE_OUT \\
    --num_train_epochs 1 \\
    --per_device_train_batch_size $FINETUNE_BATCH \\
    --gradient_accumulation_steps $FINETUNE_GRAD_AC \\
    --save_strategy no \\
    --learning_rate 2e-4 \\
    --weight_decay 0. \\
    --warmup_ratio 0.03 \\
    --lr_scheduler_type cosine \\
    --logging_steps 1 \\
    --tf32 True \\
    --model_max_length 2048 \\
    --gradient_checkpointing True \\
    --dataloader_num_workers 4 \\
    --lazy_preprocess True \\
    --report_to wandb
"""

# ---------------------------------------------------------------------------
# Generate
# ---------------------------------------------------------------------------


def generate():
    for m in MODELS:
        slug = m["slug"]
        text = JOB_TEMPLATE.format(
            slug=slug,
            model_id=m["id"],
            family=m["family"],
            llm_model=LLM_MODEL,
            pretrain_batch=PRETRAIN_BATCH,
            pretrain_grad_ac=PRETRAIN_GRAD_AC,
            finetune_batch=FINETUNE_BATCH,
            finetune_grad_ac=FINETUNE_GRAD_AC,
        )
        out_path = OUT_DIR / f"{slug}.job"
        out_path.write_text(text)
        os.chmod(out_path, 0o755)

    print(f"Generated {len(MODELS)} job scripts in {OUT_DIR}/")
    for m in MODELS:
        print(f"  {m['slug']:25s}  [{m['family']:6s}]  {m['id']}")


if __name__ == "__main__":
    generate()
